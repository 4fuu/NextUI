#!/usr/bin/env python3
"""Build one signed local package for the host install tests.

Writes <out-dir>/Demo.pakz, Demo.manifest.json and Demo.manifest.sig: a
nextui-update-v1 manifest generated by the real nextupd tool over a real zip, and
a detached Ed25519 signature made with the committed test-only seed. Nothing here
creates or stores a production key, and no network, feed, store source or real
device is involved.

The default is a minimal application: a pak.json manifest, an executable
launch.sh that records that it ran, and a small binary. That is exactly the shape
the launcher discovers (a .pak directory containing launch.sh), so the same
package proves the install path and the launcher discovery path. --kind system
builds the same three file names with a system archive instead: the validly
signed system package a racing writer would swap into the package folder after
the page scanned it.

Usage:
  make_app_package.py <nextupd-binary> <fixtures-dir> <out-dir>
      [--version v1.0.0] [--id com.example.demo] [--name Demo] [--platform universal]
      [--kind app|system] [--min-system v6.0.0] [--unsigned]

Prints the three paths, one per line: package, manifest, signature.
"""

import base64
import json
import os
import subprocess
import sys
import zipfile

KEY_ID = "nextui-test-only-1"


def parse_args(argv):
    options = {
        "version": "v1.0.0",
        "id": "com.example.demo",
        "name": "Demo",
        "platform": "universal",
        "kind": "app",
        "min_system": None,
        "unsigned": False,
    }
    positional = []
    index = 0
    while index < len(argv):
        argument = argv[index]
        if argument.startswith("--"):
            key = argument[2:]
            if key == "unsigned":
                options["unsigned"] = True
                index += 1
                continue
            index += 1
            if index >= len(argv):
                raise SystemExit(f"make_app_package: {argument} requires a value")
            if key == "min-system":
                options["min_system"] = argv[index]
            elif key in options:
                options[key] = argv[index]
            else:
                raise SystemExit(f"make_app_package: unknown option {argument}")
        else:
            positional.append(argument)
        index += 1
    if len(positional) != 3:
        raise SystemExit(
            "usage: make_app_package.py <nextupd> <fixtures-dir> <out-dir> [options]"
        )
    return positional[0], positional[1], positional[2], options


def make_key_der(fixtures, out_dir):
    """The committed test seed as an Ed25519 DER key, for openssl signing only.

    Written into the caller's output directory, never into the repository: the
    seed is committed, the derived key is a build artifact.
    """
    seed_hex = os.path.join(fixtures, "test-ed25519-seed.hex")
    with open(seed_hex, "r", encoding="ascii") as handle:
        seed = bytes.fromhex(handle.read().strip())
    key_der = os.path.join(out_dir, "test-key.der")
    with open(key_der, "wb") as handle:
        handle.write(bytes.fromhex("302e020100300506032b657004220420") + seed)
    return key_der


def sign_manifest(manifest_path, signature_path, key_der):
    detached = signature_path + ".bin"
    subprocess.run(
        ["openssl", "pkeyutl", "-sign", "-rawin", "-inkey", key_der,
         "-keyform", "DER", "-in", manifest_path, "-out", detached],
        check=True, capture_output=True, text=True,
    )
    with open(detached, "rb") as handle:
        payload = base64.b64encode(handle.read()).decode("ascii")
    with open(signature_path, "w", encoding="ascii") as handle:
        handle.write(f"nextui-signature-v1\n{KEY_ID}\n{payload}\n")
    os.unlink(detached)


def write_zip(path, entries):
    with zipfile.ZipFile(path, "w") as archive:
        for entry in entries:
            info = zipfile.ZipInfo(entry["name"], (2026, 1, 1, 0, 0, 0))
            info.create_system = 3
            info.external_attr = entry.get("mode", 0o100644) << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, entry.get("data", b""))


def system_entries(version, platform):
    """The system archive shape: every path under .system/, with version.txt
    equal to the signed version, which is what the system installer applies."""
    return [
        {"name": ".system/version.txt", "data": version.encode() + b"\n",
         "mode": 0o100644},
        {"name": f".system/{platform}/bin/nextui.elf",
         "data": b"\x7fELF" + version.encode(), "mode": 0o100755},
        {"name": f".system/{platform}/paks/MinUI.pak/launch.sh",
         "data": b"#!/bin/sh\n", "mode": 0o100755},
    ]


def app_entries(version, app_id, name):
    launch = (
        "#!/bin/sh\n"
        "# Minimal test application: records that the launcher started it.\n"
        "echo ran > \"$(dirname \"$0\")/ran\"\n"
        "exit 0\n"
    ).encode()
    return [
        {"name": "launch.sh", "data": launch, "mode": 0o100755},
        {"name": "demo", "data": b"\x7fELF" + version.encode(), "mode": 0o100755},
        {"name": "pak.json",
         "data": json.dumps({"id": app_id, "name": name,
                             "version": version}).encode()},
    ]


def main():
    tool, fixtures, out_dir, options = parse_args(sys.argv[1:])
    if options["kind"] not in ("app", "system"):
        raise SystemExit("make_app_package: --kind must be app or system")
    os.makedirs(out_dir, exist_ok=True)
    # A system manifest must name a .zip archive, so the system shape cannot use
    # the .pakz name the app page scans for.
    package = os.path.join(out_dir, "Demo.zip" if options["kind"] == "system"
                           else "Demo.pakz")
    manifest = os.path.join(out_dir, "Demo.manifest.json")
    signature = os.path.join(out_dir, "Demo.manifest.sig")

    # A system package needs a concrete platform and the derived system id, so a
    # universal request becomes the platform these tests install against.
    platform = options["platform"]
    app_id = options["id"]
    if options["kind"] == "system":
        if platform == "universal":
            platform = "tg5040"
        app_id = f"nextui.system.{platform}"
        entries = system_entries(options["version"], platform)
    else:
        entries = app_entries(options["version"], app_id, options["name"])
    write_zip(package, entries)

    args = [tool, "manifest", "--package", package, "--id", app_id,
            "--kind", options["kind"], "--version", options["version"], "--platform",
            platform, "--out", manifest]
    if options["min_system"]:
        args += ["--min-system", options["min_system"]]
    subprocess.run(args, check=True, capture_output=True, text=True)

    if not options["unsigned"]:
        sign_manifest(manifest, signature, make_key_der(fixtures, out_dir))

    print(package)
    print(manifest)
    if not options["unsigned"]:
        print(signature)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
